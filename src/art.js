  /** 程序化符文：给每条词条生成一枚独一无二的徽记。
   *  用 id 的哈希做种子，再加上左右/上下镜像对称 —— 对称性能让随机图案看起来"像被设计过的符号"。
   *  好处：40 条词条不用手绘 40 张图，加词条零成本，而且每枚都是原创。 */
  function runeBits(id) {
    let h = 2166136261;
    for (let i = 0; i < id.length; i++) { h ^= id.charCodeAt(i); h = Math.imul(h, 16777619); }
    const rnd = () => { h ^= h << 13; h >>>= 0; h ^= h >>> 17; h ^= h << 5; h >>>= 0; return h / 4294967296; };
    const g = [];
    for (let y = 0; y < 8; y++) g.push(new Array(8).fill(0));
    // 只在上半部分撒点，然后上下镜像
    for (let y = 0; y < 4; y++) for (let x = 0; x < 8; x++) {
      const v = rnd() < 0.42 ? (rnd() < 0.45 ? 2 : 1) : 0;
      g[y][x] = v;
      g[7 - y][x] = v;
    }
    // 左右镜像（取左侧 3 列，镜像到右侧）
    for (let y = 0; y < 8; y++) for (let x = 0; x < 3; x++) g[y][7 - x] = g[y][x];
    // 外框：让它读起来像一枚"符"
    for (let i = 1; i < 7; i++) { if (!g[0][i]) g[0][i] = 3; if (!g[7][i]) g[7][i] = 3; if (!g[i][0]) g[i][0] = 3; if (!g[i][7]) g[i][7] = 3; }
    g[0][0] = g[0][7] = g[7][0] = g[7][7] = 3;
    return g;
  }

  /** 画一枚词条符文。col 是三档颜色 [亮, 中, 暗]。 */
  function drawRune(ctx, id, x, y, px, cols) {
    const g = runeBits(id);
    for (let r = 0; r < 8; r++) for (let c = 0; c < 8; c++) {
      const v = g[r][c];
      if (!v) continue;
      ctx.fillStyle = cols[v - 1] || '#fff';
      ctx.fillRect(x + c * px, y + r * px, px, px);
    }
  }

